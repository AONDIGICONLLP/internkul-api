#!/usr/bin/env python3
"""
Convert the legacy Laravel/MySQL dump (internku_db.sql) into PostgreSQL INSERTs
for the new LMS schema.   Usage:

    python3 scripts/convert_legacy_mysql.py path/to/internku_db.sql > db/seed/002_legacy_data.sql

What it does
  * domains, batch_timings            -> copied
  * tracks                            -> courses + course_plans (JSON duration_options is exploded into rows)
  * users (admin)                     -> users (role=admin). `$2y$` bcrypt hashes are re-labelled `$2b$`
  * students                          -> users(role=student) + student_profiles
  * "…[07:30_AM] - 45 Days (PAID: ₹1499 | ID: pay_xxx)" free-text stored in students.interested_course_name
                                      -> enrollments + payments(provider='legacy', status='paid')
  * credentials, inquiries            -> copied
  * api_tokens / sessions / cache / jobs are intentionally NOT migrated (re-login required)

Legacy students never had a server-side password (it lived in the browser), so they are imported with
password_hash = NULL and activate their account through "Forgot password".
"""
import json
import re
import sys

CODE_MAP = {
    "mern-full-stack": "MERN", "flutter-mobile": "FLUT", "python-development": "PYTH",
    "core-java": "JAVA", "dotnet-core": "DOTN", "power-bi-sql": "PBSQ", "ai-ml": "AIML",
    "modern-seo-organic-growth": "SEO",
}

# ───────────────────────── minimal MySQL INSERT parser ─────────────────────────
ESC = {"n": "\n", "r": "\r", "t": "\t", "0": "\0", "Z": "\x1a", "b": "\b"}


def parse_values(blob: str):
    """Parse `(1,'a',NULL),(2,'b',3)` into python lists."""
    rows, i, n = [], 0, len(blob)
    while i < n:
        if blob[i] != "(":
            i += 1
            continue
        i += 1
        row = []
        while True:
            while blob[i] in " \n\r\t":
                i += 1
            c = blob[i]
            if c == "'":
                i += 1
                buf = []
                while True:
                    ch = blob[i]
                    if ch == "\\":
                        nxt = blob[i + 1]
                        buf.append(ESC.get(nxt, nxt))
                        i += 2
                    elif ch == "'":
                        if blob[i + 1] == "'":
                            buf.append("'")
                            i += 2
                        else:
                            i += 1
                            break
                    else:
                        buf.append(ch)
                        i += 1
                row.append("".join(buf))
            else:
                j = i
                while blob[j] not in ",)":
                    j += 1
                tok = blob[i:j].strip()
                i = j
                if tok.upper() == "NULL":
                    row.append(None)
                else:
                    row.append(float(tok) if "." in tok else int(tok))
            while blob[i] in " \n\r\t":
                i += 1
            if blob[i] == ",":
                i += 1
                continue
            if blob[i] == ")":
                i += 1
                break
        rows.append(row)
    return rows


def read_table(sql: str, table: str):
    rows = []
    pat = re.compile(r"INSERT INTO `%s` \((.*?)\) VALUES\s*(.*?);\n" % table, re.S)
    for m in pat.finditer(sql):
        cols = [c.strip("` ") for c in m.group(1).split(",")]
        for r in parse_values(m.group(2)):
            rows.append(dict(zip(cols, r)))
    return rows


# ───────────────────────────── SQL literal helpers ─────────────────────────────
def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def j(v, default="[]"):
    if v in (None, ""):
        return "'%s'::jsonb" % default
    if isinstance(v, str):
        v = json.loads(v)
    return q(json.dumps(v, ensure_ascii=False)) + "::jsonb"


def ts(v):
    return q(v) + "::timestamptz" if v else "NULL"


def main(path):
    sql = open(path, encoding="utf8").read()
    out = []
    emit = out.append
    emit("-- Generated by scripts/convert_legacy_mysql.py — legacy data import\nBEGIN;\n")

    # domains
    for d in read_table(sql, "domains"):
        emit("INSERT INTO domains(slug,label,sort_order) VALUES (%s,%s,%s) ON CONFLICT (slug) DO NOTHING;"
             % (q(d["slug"]), q(d["label"]), d["sort_order"]))
    # timings
    for t in read_table(sql, "batch_timings"):
        emit("INSERT INTO batch_timings(timing_id,time_label,name,status,suitable_for) VALUES (%s,%s,%s,%s,%s) "
             "ON CONFLICT (timing_id) DO NOTHING;"
             % (q(t["timing_id"]), q(t["time_label"]), q(t["name"]), q(t["status"]), q(t["suitable_for"])))

    # admin users
    for u in read_table(sql, "users"):
        role = "admin" if u["role"] == "admin" else "student"
        if role != "admin":
            continue
        h = (u["password"] or "").replace("$2y$", "$2b$", 1)
        emit("INSERT INTO users(name,email,password_hash,role,is_active,email_verified_at,created_at) "
             "VALUES (%s,%s,%s,'admin',true,now(),%s) ON CONFLICT (email) DO NOTHING;"
             % (q(u["name"]), q(u["email"]), q(h), ts(u["created_at"])))

    # courses + plans
    plan_labels = {}  # (slug, label) -> code
    for t in read_table(sql, "tracks"):
        slug = t["slug"]
        code = CODE_MAP.get(slug) or re.sub(r"[^A-Z]", "", "".join(w[0] for w in slug.split("-")).upper())[:4] or "CRS"
        avail = json.loads(t["available_batches"] or "[]")
        emit(("INSERT INTO courses(slug,code,name,short_name,domain,summary,detailed_description,technologies,"
              "primary_stack,target_degrees,available_timings,capstone,curriculum,featured,status,created_at) VALUES "
              "(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) ON CONFLICT (slug) DO NOTHING;") % (
            q(slug), q(code), q(t["name"]), q(t["short_name"]), q(t["domain"]), q(t["summary"]),
            q(t["detailed_description"]), j(t["technologies"]), j(t["primary_stack"]), j(t["target_degrees"]),
            j(avail), j(t["capstone"], "{}"), j(t["curriculum"], "{}"),
            "true" if t["featured"] else "false", q(t["status"]), ts(t["created_at"])))
        opts = json.loads(t["duration_options"] or "{}")
        for order, (pcode, o) in enumerate(opts.items()):
            plan_labels[(slug, o.get("label"))] = pcode
            emit(("INSERT INTO course_plans(course_id,code,label,tier_name,days,sessions,lab_hours,price_inr,"
                  "original_price_inr,discount_percent,academic_support_eligible,lor_eligible,ppo_eligible,"
                  "synopsis_pages,features,sort_order) VALUES ((SELECT id FROM courses WHERE slug=%s),%s,%s,%s,%s,%s,%s,"
                  "%s,%s,%s,%s,%s,%s,%s,%s,%s) ON CONFLICT (course_id,code) DO NOTHING;") % (
                q(slug), q(pcode), q(o.get("label", pcode)), q(o.get("tierName")), o.get("days", 1),
                o.get("sessions", 0), o.get("labHours", 0), o.get("priceINR", 0), o.get("originalPriceINR", 0),
                o.get("discountPercent", 0), q(bool(o.get("academicSupportEligible"))), q(bool(o.get("lorEligible"))),
                q(bool(o.get("ppoEligible"))), o.get("synopsisPages", 0), j(o.get("features", [])), order))

    # students (+ enrolments / payments recovered from the free-text field)
    pay_re = re.compile(r"\[(\d\d:\d\d_[AP]M)\]\s*-\s*(.+?)\s*\(PAID:\s*₹?([\d.]+)\s*\|\s*ID:\s*(pay_\w+)\)")
    for s in read_table(sql, "students"):
        emit(("INSERT INTO users(name,email,phone,country_code,password_hash,role,avatar_url,is_active,created_at) "
              "VALUES (%s,%s,%s,%s,NULL,'student',%s,true,%s) ON CONFLICT (email) DO NOTHING;") % (
            q(s["full_name"]), q(s["email"]), q(s["phone"]), q(s["country_code"]), q(s["avatar_url"]),
            ts(s["created_at"])))
        emit(("INSERT INTO student_profiles(user_id,student_code,first_name,last_name,permanent_address,"
              "interested_course_slug,interested_topics,auth_method,created_at) VALUES "
              "((SELECT id FROM users WHERE email=%s),%s,%s,%s,%s,%s,%s,%s,%s) ON CONFLICT (student_code) DO NOTHING;") % (
            q(s["email"]), q(s["student_id"]), q(s["first_name"]), q(s["last_name"]), q(s["permanent_address"]),
            q(s["interested_course_slug"]), j(s["interested_topics"]), q(s["auth_method"]), ts(s["created_at"])))
        m = pay_re.search(s["interested_course_name"] or "")
        slug = s["interested_course_slug"]
        if m and slug:
            timing, label, amount, pay_id = m.groups()
            pcode = plan_labels.get((slug, label.strip()))
            plan_sql = ("(SELECT id FROM course_plans WHERE code=%s AND course_id=(SELECT id FROM courses WHERE slug=%s))"
                        % (q(pcode), q(slug))) if pcode else "NULL"
            who = "(SELECT id FROM users WHERE email=%s)" % q(s["email"])
            course = "(SELECT id FROM courses WHERE slug=%s)" % q(slug)
            emit(("INSERT INTO enrollments(student_id,course_id,plan_id,timing_id,status,amount_due,enrolled_at) "
                  "SELECT %s,%s,%s,%s,'active',%s,%s WHERE NOT EXISTS "
                  "(SELECT 1 FROM enrollments WHERE student_id=%s AND course_id=%s AND status<>'cancelled');") % (
                who, course, plan_sql, q(timing), amount, ts(s["created_at"]), who, course))
            emit(("INSERT INTO payments(enrollment_id,student_id,provider,status,amount,receipt_no,razorpay_payment_id,"
                  "method,paid_at,notes) VALUES ((SELECT id FROM enrollments WHERE student_id=%s AND course_id=%s "
                  "ORDER BY id DESC LIMIT 1),%s,'legacy','paid',%s,'LEG-'||nextval('receipt_seq'),%s,'razorpay',%s,%s) "
                  "ON CONFLICT (razorpay_payment_id) DO NOTHING;") % (
                who, course, who, amount, q(pay_id), ts(s["created_at"]), q("Imported from legacy students.interested_course_name")))

    # credentials
    for c in read_table(sql, "credentials"):
        emit(("INSERT INTO credentials(credential_id,student_name,student_initials,degree,college_name,track_slug,"
              "track_name,course_id,duration,duration_days,issue_date,verification_status,verified_at,skills,github_url,"
              "live_deployment_url,capstone_title,capstone_description,lor_qualified,ppo_qualified,code_quality,"
              "milestone_sprints,technical_interview,total_score,verified_by) VALUES (%s,%s,%s,%s,%s,%s,%s,"
              "(SELECT id FROM courses WHERE slug=%s),%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) "
              "ON CONFLICT (credential_id) DO NOTHING;") % (
            q(c["credential_id"]), q(c["student_name"]), q(c["student_initials"]), q(c["degree"]), q(c["college_name"]),
            q(c["track_slug"]), q(c["track_name"]), q(c["track_slug"]), q(c["duration"]), c["duration_days"],
            q(c["issue_date"]), q(c["verification_status"]), ts(c["verified_at"]), j(c["skills"]), q(c["github_url"]),
            q(c["live_deployment_url"]), q(c["capstone_title"]), q(c["capstone_description"]),
            q(bool(c["lor_qualified"])), q(bool(c["ppo_qualified"])), c["code_quality"], c["milestone_sprints"],
            c["technical_interview"], c["total_score"], q(c["verified_by"])))

    # inquiries (guarded so re-running the import never creates duplicates)
    for r in read_table(sql, "inquiries"):
        emit(("INSERT INTO inquiries(type,name,email,phone,enquiry_category,interested_course,institution_name,"
              "designation,number_of_students,preferred_duration,preferred_training_window,message,status,admin_notes,"
              "created_at) SELECT %s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s WHERE NOT EXISTS "
              "(SELECT 1 FROM inquiries WHERE type=%s AND email=%s AND created_at=%s);") % (
            q(r["type"]), q(r["name"]), q(r["email"]), q(r["phone"]), q(r["enquiry_category"]), q(r["interested_course"]),
            q(r["institution_name"]), q(r["designation"]), q(r["number_of_students"]), q(r["preferred_duration"]),
            q(r["preferred_training_window"]), q(r["message"]), q(r["status"]), q(r["admin_notes"]), ts(r["created_at"]),
            q(r["type"]), q(r["email"]), ts(r["created_at"])))

    emit("\nCOMMIT;")
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
